package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/Input/Drag"
)

func main() {
	genName = "Start/extension/gen"
	repoRoot, _ := roots()

	var b strings.Builder
	fmt.Fprintln(&b, "// GENERATED by Start/extension/gen — do not edit.")
	fmt.Fprintln(&b, "// Source: Stdin's record_kinds.go.")
	fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "export const IN_KIND_RAW_INPUT = %d;\n\n", Drag.KindRawInput)

	wirePath := filepath.Join(repoRoot, "Start", "extension", "wire-gen.ts")
	if err := os.WriteFile(wirePath, []byte(b.String()), 0o644); err != nil {
		fatalf("write %s: %v", wirePath, err)
	}
	announce(wirePath, 1, "record kinds")

	for dir, up := range map[string]string{
		filepath.Join("Start", "extension"):            "../../Categories/",
		filepath.Join("Start", "extension", "webview"): "../../../Categories/",
	} {
		outPath := filepath.Join(repoRoot, dir, "messages.ts")
		body := "// GENERATED by Start/extension/gen — do not edit.\n" +
			"// Regenerate with: go generate ./...\n\n" +
			strings.ReplaceAll(tsMessagesSource, `from "../`, `from "`+up)
		if err := os.WriteFile(outPath, []byte(body), 0o644); err != nil {
			fatalf("write %s: %v", outPath, err)
		}
		announce(outPath, 1, "webview→host message union")
	}
}
