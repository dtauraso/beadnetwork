package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/Scene/Drag"
)

func main() {
	genName = "Start/extension/runner/gen"
	repoRoot, _ := roots()

	var b strings.Builder
	fmt.Fprintln(&b, "// GENERATED by Start/extension/runner/gen — do not edit.")
	fmt.Fprintln(&b, "// Source: Drag's kinds.go — the runner names one input slot file per event kind.")
	fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "export const IN_EVENT_KINDS = [")
	for i, v := range Drag.EventKinds {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", v)
	}
	fmt.Fprintln(&b, "] as const;")
	fmt.Fprintln(&b)

	outPath := filepath.Join(repoRoot, "Start", "extension", "runner", "wire-gen.ts")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}
	announce(outPath, len(Drag.EventKinds), "event kinds")
}
