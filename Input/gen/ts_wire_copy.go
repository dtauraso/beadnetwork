package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var tsWireTargets = []struct {
	dir    string
	lists  []string
	kinds  []string
	attr   bool
	writer bool
}{
	{dir: "Node", attr: true, writer: true},
	{dir: "Node/Edge", attr: true, writer: true},
	{dir: "Scene", attr: true, writer: true},
	{dir: "Overlay", attr: true, writer: true},
	{dir: "Chrome/Panels/Panel", attr: true, writer: true},
	{dir: "Clock", attr: true, writer: true},
	{dir: "Input/Drag", writer: true,
		lists: []string{"eventKinds=", "hitKinds="}, kinds: []string{"raw-input"}},
	{dir: "extension", kinds: []string{"raw-input"}},
	{dir: "extension/runner", lists: []string{"eventKinds="}},
}

var tsListName = map[string]string{
	"eventKinds=":  "IN_EVENT_KINDS",
	"hitKinds=":    "IN_HIT_KINDS",
	"updateKinds=": "IN_UPDATE_KINDS",
	"updateAttrs=": "IN_UPDATE_ATTRS",
}

var tsKindConstName = map[string]string{
	"save":        "IN_KIND_SAVE",
	"raw-input":   "IN_KIND_RAW_INPUT",
	"edit-update": "IN_KIND_EDIT_UPDATE",
}

func copyTSWireVocabulary(srcRoot string, fp wireSource) {
	for _, t := range tsWireTargets {
		var b strings.Builder
		fmt.Fprintln(&b, "// GENERATED by Input/gen — do not edit.")
		fmt.Fprintln(&b, "// Source: the input layout declared in Input/gen.")
		fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
		fmt.Fprintln(&b)

		kinds := append([]string{}, t.kinds...)
		if t.attr {
			kinds = append(kinds, "edit-update")
		}
		for _, k := range kinds {
			fmt.Fprintf(&b, "export const %s = %s;\n", tsKindConstName[k], fp.KindValue(k))
		}
		if len(kinds) > 0 {
			fmt.Fprintln(&b)
		}

		lists := append([]string{}, t.lists...)
		if t.attr {
			lists = append(lists, "updateKinds=", "updateAttrs=")
		}
		sort.Strings(lists)
		for _, m := range lists {
			if m == "updateKinds=" {
				fmt.Fprintln(&b, "// EDIT_UPDATE_KINDS_START")
			}
			fmt.Fprintf(&b, "export const %s = [", tsListName[m])
			for i, v := range fp.List(m) {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", v)
			}
			fmt.Fprintln(&b, "] as const;")
			if m == "updateKinds=" {
				fmt.Fprintln(&b, "// EDIT_UPDATE_KINDS_END")
			}
			fmt.Fprintln(&b)
		}

		if t.writer {
			b.WriteString(tsByteWriterSource)
			b.WriteString("\n")
		}
		if t.attr {
			b.WriteString(tsAttrIndexSource)
		}

		outPath := filepath.Join(srcRoot, filepath.FromSlash(t.dir), "wire-gen.ts")
		if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
			fatalf("write %s: %v", outPath, err)
		}
		announce(outPath, len(lists)+len(kinds), "wire vocabulary for "+t.dir)
	}

	for dir, up := range map[string]string{
		"extension":         "../",
		"extension/webview": "../../",
	} {
		outPath := filepath.Join(srcRoot, filepath.FromSlash(dir), "messages.ts")
		body := "// GENERATED by Input/gen — do not edit.\n" +
			"// Regenerate with: go generate ./...\n\n" +
			strings.ReplaceAll(tsMessagesSource, `from "../`, `from "`+up)
		if err := os.WriteFile(outPath, []byte(body), 0o644); err != nil {
			fatalf("write %s: %v", outPath, err)
		}
		announce(outPath, 1, "webview→host message union for "+dir)
	}
}
