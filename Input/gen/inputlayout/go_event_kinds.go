package inputlayout

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
)

func WriteGoEventKinds(outPath string, fp *inputLayoutFingerprint) error {
	var buf bytes.Buffer
	fmt.Fprintln(&buf, `// GENERATED by Input/gen — do not edit.`)
	fmt.Fprintln(&buf, `// Source: the eventKinds list in InputLayoutFingerprint.`)
	fmt.Fprintln(&buf, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(&buf, `//`)
	fmt.Fprintln(&buf, `// The same ordering TS gets as IN_EVENT_KINDS. Each kind has its own slot file`)
	fmt.Fprintln(&buf, `// under view/input/, so a move cannot overwrite the press that preceded it, and`)
	fmt.Fprintln(&buf, `// this list IS the read order: a press is applied before the motion it started.`)
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, `package Drag`)
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, `var EventKinds = []string{`)
	for _, name := range fp.eventKinds {
		fmt.Fprintf(&buf, "\t%q,\n", name)
	}
	fmt.Fprintln(&buf, `}`)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format event kinds: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0o644)
}
