package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/dtauraso/wirefold/scripts/genpaths"
)

var wireTargets = []struct {
	dir   string
	pkg   string
	lists []string // fingerprint markers this concern reads
	kinds []string // record kind constants it names
	attr  bool     // needs AttrIndex
	enum  bool     // needs EnumAt
}{
	{dir: "Node", pkg: "Node", attr: true},
	{dir: "Node/Edge", pkg: "edge", attr: true},
	{dir: "Scene", pkg: "Scene", attr: true},
	{dir: "Overlay", pkg: "Overlay", attr: true},
	{dir: "Chrome/Panels/Panel", pkg: "Panel", attr: true},
	{dir: "Clock", pkg: "clock", attr: true},
	{dir: "Input/Drag", pkg: "Drag", enum: true,
		lists: []string{"eventKinds=", "hitKinds="}, kinds: []string{"raw-input"}},
	{dir: "Input/Stdin", pkg: "Stdin", enum: true,
		lists: []string{"updateKinds="}, kinds: []string{"save", "raw-input", "edit-update"}},
	{dir: "Input/File", pkg: "File", lists: []string{"eventKinds="}},
}

var listVarName = map[string]string{
	"eventKinds=":   "InEventKinds",
	"hitKinds=":     "InHitKinds",
	"updateKinds=":  "InUpdateKinds",
	"updateAttrs=":  "InUpdateAttrs",
	"overlayFlags=": "InOverlayFlags",
	"panelFlags=":   "InPanelFlags",
}

var kindConstName = map[string]string{
	"save":        "InKindSave",
	"raw-input":   "InKindRawInput",
	"edit-update": "InKindEditUpdate",
}

type wireSource interface {
	List(marker string) []string
	KindValue(name string) string
}

func copyWireVocabulary(srcRoot string, fp wireSource) {
	for _, t := range wireTargets {
		var b strings.Builder
		fmt.Fprintln(&b, "// GENERATED by src/Input/gen — do not edit.")
		fmt.Fprintln(&b, "// Source: the input layout declared in src/Input/gen.")
		fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
		fmt.Fprintln(&b)
		fmt.Fprintf(&b, "package %s\n\n", t.pkg)

		if len(t.kinds) > 0 {
			fmt.Fprintln(&b, "const (")
			for _, k := range t.kinds {
				fmt.Fprintf(&b, "\t%s = %s\n", kindConstName[k], fp.KindValue(k))
			}
			fmt.Fprintln(&b, ")")
			fmt.Fprintln(&b)
		}

		lists := append([]string{}, t.lists...)
		if t.attr {
			lists = append(lists, "updateAttrs=")
		}
		sort.Strings(lists)
		for _, m := range lists {
			fmt.Fprintf(&b, "var %s = []string{", listVarName[m])
			for i, v := range fp.List(m) {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", v)
			}
			fmt.Fprintln(&b, "}")
			fmt.Fprintln(&b)
		}

		if t.attr {
			fmt.Fprintf(&b, `func attrIndex(attr string) byte {
	for i, a := range InUpdateAttrs {
		if a == attr {
			return byte(i)
		}
	}
	panic("%s.attrIndex: no wire byte exists for update attribute " + attr +
		"; the attr list this package was generated with does not carry it, so an edit naming " +
		"it could never be encoded. Declare it in src/Input/gen's input layout and regenerate, " +
		"in the same commit as the decoder that reads it.")
}

`, t.pkg)
		}

		if t.enum {
			fmt.Fprintln(&b, `func enumAt(list []string, i byte) string {
	if int(i) >= len(list) {
		return ""
	}
	return list[i]
}`)
		}

		outPath := filepath.Join(srcRoot, filepath.FromSlash(t.dir), "wire_gen.go")
		if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
			genpaths.Fatalf("write %s: %v", outPath, err)
		}
		genpaths.Announce(outPath, len(lists)+len(t.kinds), fmt.Sprintf("wire vocabulary for %s", t.pkg))
	}
}
