package buflayout

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"strings"
)

func WriteBufferLayoutTS(headerPath, rowsPathA, rowsPathB, singletonsPath string, schema BufLayoutSchema) error {
	fp := buildBufFingerprint(schema)

	if err := writeBufferLayoutTSHeader(headerPath, schema, fp); err != nil {
		return err
	}
	if err := writeBufferLayoutTSRows(rowsPathA, rowsPathB, schema); err != nil {
		return err
	}
	if err := writeBufferLayoutTSSingletons(singletonsPath, schema); err != nil {
		return err
	}
	return nil
}

func writeBufferLayoutTSHeader(outPath string, schema BufLayoutSchema, fp string) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by src/schema/buffer-layout/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/schema/buffer-layout/layout_version.go  Regenerate: go generate ./...`)
	fmt.Fprintf(w, "// BUF_LAYOUT_FINGERPRINT: %s\n", fp)
	fmt.Fprintln(w)
	fmt.Fprintf(w, "/** Schema version — must match BufLayoutVersion in Buffer/bufschema/layout.go. */\n")
	fmt.Fprintf(w, "export const BUF_LAYOUT_VERSION = %d;\n", schema.version)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `/** FNV-1a over BUF_LAYOUT_FINGERPRINT above — the layout this BUNDLE was built for.`)
	fmt.Fprintln(w, ` * Every VIEW frame carries Go's copy; the decoder compares them and refuses a frame`)
	fmt.Fprintln(w, ` * from a different layout rather than decoding its bytes into the wrong columns.`)
	fmt.Fprintln(w, ` * Derived from the fingerprint, so it cannot be forgotten the way a hand-bumped`)
	fmt.Fprintln(w, ` * version number can. */`)
	fmt.Fprintf(w, "export const BUF_LAYOUT_FINGERPRINT_HASH = %d;\n", fnv1aHash(fp))
	fmt.Fprintln(w)
	fmt.Fprintf(w, "/** Fixed interior-grid slots per node — must match BufInteriorSlotsPerNode in Buffer/bufschema/layout.go.\n")
	fmt.Fprintf(w, " * Generated (part of BUF_LAYOUT_FINGERPRINT): a mismatch fails check-buffer-layout-parity.sh. */\n")
	fmt.Fprintf(w, "export const INTERIOR_SLOTS_PER_NODE = %d;\n", schema.interiorSlotsPerNode)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `/** Byte width of the retired combined-snapshot frame's header. The combined SCENE/BEAD/`)
	fmt.Fprintln(w, ` * NODE/EDGE frame is gone entirely — each goroutine now streams its own per-owner frame`)
	fmt.Fprintln(w, ` * (VIEW/EDGE_STREAM/NODE_STREAM/INTERIOR_STREAM — see frame-tags.ts and`)
	fmt.Fprintln(w, ` * memory/feedback/architecture/bridge/feedback_no_single_writer_bridge.md); this constant is a historical layout`)
	fmt.Fprintln(w, ` * marker, not consumed by any live decoder: [tick:u32][layoutLinkCount:u32] */`)
	fmt.Fprintln(w, `export const BUF_HEADER_SIZE = 8;`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `/** Sentinel Node KindId value meaning "unknown kind" (matches KindIDUnknown in Buffer/node_kind_id_gen.go). */`)
	fmt.Fprintln(w, `export const UNKNOWN_KIND_ID = 0xff;`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `export * from './buffer-layout-rows-gen';`)
	if blocks := rowBlocks(schema); len(blocks[rowBlockSplit(len(blocks)):]) > 0 {
		fmt.Fprintln(w, `export * from './buffer-layout-rows2-gen';`)
	}
	fmt.Fprintln(w, `export * from './buffer-layout-singletons-gen';`)

	w.Flush()
	return os.WriteFile(outPath, buf.Bytes(), 0644)
}

func writeTSBlockConstsAndReaders(w *bufio.Writer, blk bufBlock, singleton bool) {
	sep := strings.Repeat("─", 60-len(blk.name)-9)
	fmt.Fprintf(w, "// ── %s block %s\n", blk.name, sep)
	for _, c := range blk.columns {
		fmt.Fprintf(w, "export const %-35s = %d; // %s\n", colTSName(blk.name, c.name), c.offset, c.bufType)
	}
	fmt.Fprintf(w, "export const %-35s = %d;\n", strideTSName(blk.name), blk.stride)
	fmt.Fprintln(w)

	stride := strideTSName(blk.name)
	for _, c := range blk.columns {
		colConst := colTSName(blk.name, c.name)
		getter := tsDataViewGetter(c.bufType)
		le := tsDataViewLE(c.bufType)
		fnName := readerFnTSName(blk.name, c.name)
		if singleton {
			fmt.Fprintf(w, "export function %s(view: DataView): number { return view.%s(%s%s); }\n",
				fnName, getter, colConst, le)
		} else {
			fmt.Fprintf(w, "export function %s(view: DataView, row: number): number { return view.%s(row * %s + %s%s); }\n",
				fnName, getter, stride, colConst, le)
		}
	}
	fmt.Fprintln(w)
}
