package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/scripts/genpaths"
	"github.com/dtauraso/wirefold/src/Chrome/Panels/SliderPanel"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(SliderPanel.ValueRelPath), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by src/Chrome/Panels/SliderPanel/gen from PanelValueNames in\n")
	b.WriteString("// panel_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The slider panel's values, in the order they sit in the block. The renderer\n")
	b.WriteString("// learns where that block is from src/Chrome/Panels/SliderPanel/paths/, which Go\n")
	b.WriteString("// writes from this same list, so neither side spells a path.\n\n")
	b.WriteString("export const SLIDER_PANEL_VALUE_NAMES = [\n")
	for _, name := range SliderPanel.PanelValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type SliderPanelValueName = (typeof SLIDER_PANEL_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genpaths.Name = "SliderPanel/gen"
	_, srcRoot := genpaths.Roots()

	dir := filepath.Join(srcRoot, "Chrome", "Panels", "SliderPanel")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		genpaths.Fatalf("write slider panel paths: %v", err)
	}
	genpaths.Announce(pathsDir, 1, "slider panel block path")

	namesPath := filepath.Join(dir, "panel-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(SliderPanel.PanelValueNames), "slider panel values")
}
