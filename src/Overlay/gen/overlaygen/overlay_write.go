package overlaygen

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
)

func WriteOverlayGen(statePath, tablesPath string, flags []overlayFlag) error {
	if err := writeOverlayStateGen(statePath, flags); err != nil {
		return err
	}
	return writeOverlayTablesGen(tablesPath, flags)
}

func writeOverlayPreamble(w *bufio.Writer, source string) {
	fmt.Fprintln(w, `// GENERATED by src/Overlay/gen — do not edit.`)
	fmt.Fprintf(w, "// Source: %s\n", source)
	fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `package Overlay`)
	fmt.Fprintln(w)
}

func writeOverlayStateGen(outPath string, flags []overlayFlag) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)
	writeOverlayPreamble(w, "OVERLAY_FLAG_NAMES in src/Input/Codec/messages.ts.")

	writeOverlayStateStruct(w, flags)
	writeOverlaySetFlagHelper(w)
	writeOverlayToggleMethods(w, flags)
	writeOverlaySetGuideVisibility(w)

	w.Flush()
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format overlay_state.go: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0644)
}

func writeOverlayTablesGen(outPath string, flags []overlayFlag) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)
	writeOverlayPreamble(w, "OVERLAY_FLAG_NAMES in src/Input/Codec/messages.ts.")

	writeOverlayDefaultConstructor(w, flags)
	writeOverlayTogglesMap(w, flags)
	writeOverlayBreadcrumbTables(w, flags)

	w.Flush()
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format overlay_tables_gen.go: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0644)
}

func writeOverlayStateStruct(w *bufio.Writer, flags []overlayFlag) {
	fmt.Fprintln(w, `// OverlayState groups the per-toggle overlay-visibility booleans and their`)
	fmt.Fprintln(w, `// flip/emit logic. Owned by UIState (ui.OV); Wiring's stdin reader's OverlayToggles`)
	fmt.Fprintln(w, `// method-expression table binds these methods directly.`)
	fmt.Fprintln(w, `type OverlayState struct {`)
	for _, f := range flags {
		fmt.Fprintf(w, "\t%s bool\n", exportField(f.field))
	}
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
}

func writeOverlaySetFlagHelper(w *bufio.Writer) {
	fmt.Fprintln(w, `// setFlag flips *field. Shared body of the uniform Toggle* methods. The RowEvent`)
	fmt.Fprintln(w, `// carrying the new value is written by the caller's own goroutine directly (see`)
	fmt.Fprintln(w, `// Wiring's stdin_dispatch.go's applyUpdate) — this no longer emits through Trace.`)
	fmt.Fprintln(w, `func (o *OverlayState) setFlag(field *bool) {`)
	fmt.Fprintln(w, "\t*field = !*field")
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
}

func writeOverlayToggleMethods(w *bufio.Writer, flags []overlayFlag) {
	for _, f := range flags {
		field := exportField(f.field)
		fmt.Fprintf(w, "// Toggle%s flips %s.\n", f.method, field)
		fmt.Fprintf(w, "func (o *OverlayState) Toggle%s() {\n", f.method)
		if f.breadcrumb != "" {
			fmt.Fprintf(w, "\to.%s = !o.%s\n", field, field)
		} else {
			fmt.Fprintf(w, "\to.setFlag(&o.%s)\n", field)
		}
		fmt.Fprintln(w, `}`)
		fmt.Fprintln(w)
		if f.accessor {
			fmt.Fprintf(w, "// %s returns the current %s.\n", f.method, field)
			fmt.Fprintf(w, "func (o *OverlayState) %s() bool {\n", f.method)
			fmt.Fprintf(w, "\treturn o.%s\n", field)
			fmt.Fprintln(w, `}`)
			fmt.Fprintln(w)
		}
	}
}

func writeOverlaySetGuideVisibility(w *bufio.Writer) {
	fmt.Fprintln(w, `// SetGuideVisibility installs an explicit-visibility snapshot wholesale (the TS`)
	fmt.Fprintln(w, `// startup push so settings survive a Go respawn).`)
	fmt.Fprintln(w, `func (o *OverlayState) SetGuideVisibility(ov OverlayState) {`)
	fmt.Fprintln(w, "\t*o = ov")
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
}
