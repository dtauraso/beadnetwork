package overlaygen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

func writeGoPaths(overlayDir string, flags []overlayFlag) error {
	var buf bytes.Buffer
	fmt.Fprintln(&buf, `// GENERATED by src/Overlay/gen — do not edit.`)
	fmt.Fprintln(&buf, `// Source: the OVERLAY_FLAGS block in src/Input/messages.ts.`)
	fmt.Fprintln(&buf, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(&buf, `//`)
	fmt.Fprintln(&buf, `// The flags ride ONE file, in this order. The order IS the layout: each value is`)
	fmt.Fprintln(&buf, `// a u32 length then that many bytes. src/Overlay/paths/block.bin hands the`)
	fmt.Fprintln(&buf, `// renderer the same path, so neither side builds this string itself.`)
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, `package Overlay`)
	fmt.Fprintln(&buf)
	fmt.Fprintf(&buf, "const BlockRelPath = %q\n", RelFile)
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, `var FlagNames = []string{`)
	for _, f := range flags {
		fmt.Fprintf(&buf, "\t%q,\n", f.flag)
	}
	fmt.Fprintln(&buf, `}`)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format overlay paths: %w", err)
	}
	if err := os.WriteFile(filepath.Join(overlayDir, "flag_paths_gen.go"), formatted, 0o644); err != nil {
		return err
	}
	return writeDefaultsTS(overlayDir, flags)
}

func writeDefaultsTS(overlayDir string, flags []overlayFlag) error {
	var b bytes.Buffer
	fmt.Fprintln(&b, `// GENERATED by src/Overlay/gen — do not edit.`)
	fmt.Fprintln(&b, `// Source: the OVERLAY_FLAGS block in src/Input/messages.ts.`)
	fmt.Fprintln(&b, `//`)
	fmt.Fprintln(&b, `// What each flag is BEFORE the block has been read. Go's DefaultOverlayState`)
	fmt.Fprintln(&b, `// turns most of them on, so defaulting to false here would blank the diagram`)
	fmt.Fprintln(&b, `// on the first frames and on any read that fails - nodeBody and nodeRing off`)
	fmt.Fprintln(&b, `// means no nodes are drawn at all.`)
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, `export const OVERLAY_FLAG_DEFAULTS: Record<string, boolean> = {`)
	for _, f := range flags {
		fmt.Fprintf(&b, "  %q: %t,\n", f.flag, f.defaultOn)
	}
	fmt.Fprintln(&b, `};`)
	return os.WriteFile(filepath.Join(overlayDir, "flag-defaults-gen.ts"), b.Bytes(), 0o644)
}
