package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/scripts/genpaths"
	bead "github.com/dtauraso/wirefold/src/Ring/Bead"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(bead.ValueRelTemplate), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by src/Ring/Bead/gen from BeadValueNames in bead_values.go —\n")
	b.WriteString("// do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// One block file per node, holding every bead in flight on the lines leaving\n")
	b.WriteString("// it. The row sits in the path, not in the file.\n\n")
	b.WriteString("export const BEAD_VALUE_NAMES = [\n")
	for _, name := range bead.BeadValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type BeadValueName = (typeof BEAD_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genpaths.Name = "Ring/Bead/gen"
	_, srcRoot := genpaths.Roots()

	dir := filepath.Join(srcRoot, "Ring", "Bead")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		genpaths.Fatalf("write bead paths: %v", err)
	}
	genpaths.Announce(pathsDir, 1, "bead block path template")

	namesPath := filepath.Join(dir, "bead-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(bead.BeadValueNames), "bead values")
}
