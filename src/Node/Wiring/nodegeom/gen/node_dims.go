package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"github.com/dtauraso/wirefold/scripts/kindscan"
)

func writeNodeDims(outPath string, kinds []kindscan.KindEntry) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by src/Node/Wiring/nodegeom/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/NodeKinds/<Kind>/SPEC.md ## View width/height fields.`)
	fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `package nodegeom`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KindDim is the render width/height for one node kind, mirroring`)
	fmt.Fprintln(w, `// NODE_DEFS[kind].width/height in node-defs.ts.`)
	fmt.Fprintln(w, `type KindDim struct{ Width, Height float64 }`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KindDims maps each runtime kind to its render dimensions.`)
	fmt.Fprintln(w, `var KindDims = map[string]KindDim{`)
	for _, e := range kinds {
		width := e.View.Width
		height := e.View.Height
		if width == "" {
			width = "110"
		}
		if height == "" {
			height = "60"
		}
		fmt.Fprintf(w, "\t%q: {Width: %s, Height: %s},\n", e.GoKind, width, height)
	}
	fmt.Fprintln(w, `}`)

	w.Flush()

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format node_dims_gen.go: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0644)
}

func writeNodeKindID(outPath string, kinds []kindscan.KindEntry) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by src/Node/Wiring/nodegeom/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/NodeKinds/<Kind>/SPEC.md + bead.Register calls.`)
	fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `package Node`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KindIDUnknown is the sentinel KindId value when a node's kind is not in kindIDMap.`)
	fmt.Fprintln(w, `const KindIDUnknown uint8 = 0xFF`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// kindIDMap maps a node's Go kind name (PascalCase) to its stable buffer KindId,`)
	fmt.Fprintln(w, `// assigned once per kind in src/NodeKinds/<Kind>/SPEC.md and never renumbered by sort`)
	fmt.Fprintln(w, `// order. Id i here ↔ NODE_DEFS_ARRAY[i] on the TS side (gaps left by a removed`)
	fmt.Fprintln(w, `// kind get an undefined placeholder there, not a shift).`)
	fmt.Fprintln(w, `var kindIDMap = map[string]uint8{`)

	byID := append([]kindscan.KindEntry(nil), kinds...)
	sort.Slice(byID, func(i, j int) bool { return byID[i].KindID < byID[j].KindID })
	for _, e := range byID {
		fmt.Fprintf(w, "\t%q: %d,\n", e.GoKind, e.KindID)
	}
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// NodeKindID returns the buffer KindId for a node's Go kind string.`)
	fmt.Fprintln(w, `// Returns KindIDUnknown (0xFF) when the kind is not in the registry.`)
	fmt.Fprintln(w, `func NodeKindID(kind string) uint8 {`)
	fmt.Fprintln(w, `	if id, ok := kindIDMap[kind]; ok {`)
	fmt.Fprintln(w, `		return id`)
	fmt.Fprintln(w, `	}`)
	fmt.Fprintln(w, `	return KindIDUnknown`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KnownKinds returns every Go kind name present in kindIDMap. IDs are stable`)
	fmt.Fprintln(w, `// and assigned once (see src/NodeKinds/<Kind>/SPEC.md kindId), so — unlike the id`)
	fmt.Fprintln(w, `// space itself — this set is NOT guaranteed contiguous or dense; a removed`)
	fmt.Fprintln(w, `// kind just leaves its id unused.`)
	fmt.Fprintln(w, `// KindAppearance is what a kind looks like in the node palette: the swatch colours`)
	fmt.Fprintln(w, `// and the description, both authored in src/NodeKinds/<Kind>/SPEC.md alongside the id.`)
	fmt.Fprintln(w, `type KindAppearance struct {`)
	fmt.Fprintln(w, `	Fill   string`)
	fmt.Fprintln(w, `	Stroke string`)
	fmt.Fprintln(w, `	Desc   string`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `var kindAppearance = map[string]KindAppearance{`)
	for _, e := range byID {
		fmt.Fprintf(w, "\t%q: {Fill: %q, Stroke: %q, Desc: %q},\n", e.GoKind, e.View.Fill, e.View.Stroke, e.View.Desc)
	}
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// AppearanceOf returns a kind's palette appearance, and false when the kind is unknown.`)
	fmt.Fprintln(w, `func AppearanceOf(kind string) (KindAppearance, bool) {`)
	fmt.Fprintln(w, `	a, ok := kindAppearance[kind]`)
	fmt.Fprintln(w, `	return a, ok`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KindNameByID is the kind at each id, with an empty string where an id is unused.`)
	fmt.Fprintln(w, `func KindNameByID() []string {`)
	fmt.Fprintln(w, `	var maxID int`)
	fmt.Fprintln(w, `	for _, id := range kindIDMap {`)
	fmt.Fprintln(w, `		if int(id) > maxID {`)
	fmt.Fprintln(w, `			maxID = int(id)`)
	fmt.Fprintln(w, `		}`)
	fmt.Fprintln(w, `	}`)
	fmt.Fprintln(w, `	out := make([]string, maxID+1)`)
	fmt.Fprintln(w, `	for k, id := range kindIDMap {`)
	fmt.Fprintln(w, `		out[id] = k`)
	fmt.Fprintln(w, `	}`)
	fmt.Fprintln(w, `	return out`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `func KnownKinds() []string {`)
	fmt.Fprintln(w, `	out := make([]string, 0, len(kindIDMap))`)
	fmt.Fprintln(w, `	for k := range kindIDMap {`)
	fmt.Fprintln(w, `		out = append(out, k)`)
	fmt.Fprintln(w, `	}`)
	fmt.Fprintln(w, `	return out`)
	fmt.Fprintln(w, `}`)

	w.Flush()
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format node_kind_id_gen.go: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0644)
}
