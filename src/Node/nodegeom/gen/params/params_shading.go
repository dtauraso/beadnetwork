package params

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/dtauraso/wirefold/src/Node/nodegeom/gen/constexpr"
)

type shadingParam struct {
	tsName string
	value  string
	isStr  bool
}

func ParseShadingParams(repoRoot, goPath string) ([]shadingParam, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, goPath, nil, 0)
	if err != nil {
		return nil, err
	}
	dir := filepath.Dir(goPath)
	var env *constexpr.Env
	var params []shadingParam
	for _, decl := range f.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.CONST {
			continue
		}
		for _, spec := range genDecl.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for i, name := range vs.Names {
				if !strings.HasPrefix(name.Name, "ShadingParam") {
					continue
				}
				if i >= len(vs.Values) {
					continue
				}
				tsName := camelToScreamingSnake(name.Name)
				if lit, ok := vs.Values[i].(*ast.BasicLit); ok {
					raw := lit.Value
					isStr := lit.Kind == token.STRING
					if isStr {
						raw = strings.Trim(raw, `"`)
					}
					params = append(params, shadingParam{tsName: tsName, value: raw, isStr: isStr})
					continue
				}
				if env == nil {
					env, err = constexpr.NewEnv(fset, repoRoot)
					if err != nil {
						return nil, err
					}
				}
				val, err := env.Eval(dir, f, vs.Values[i])
				if err != nil {
					return nil, fmt.Errorf("evaluate %s: %w", name.Name, err)
				}
				params = append(params, shadingParam{tsName: tsName, value: constValueString(val), isStr: false})
			}
		}
	}
	if len(params) == 0 {
		return nil, fmt.Errorf("no ShadingParam* constants found in %s", goPath)
	}
	return params, nil
}

func constValueString(v constant.Value) string {
	if v.Kind() == constant.Int {
		return v.ExactString()
	}
	f, _ := constant.Float64Val(v)
	return strconv.FormatFloat(f, 'g', -1, 64)
}

func WriteShadingParams(outPath string, params []shadingParam) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by src/Node/nodegeom/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/Node/nodegeom/shading_params.go ShadingParam* constants.`)
	fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(w, `//`)
	fmt.Fprintln(w, `// Go owns the shading PARAMETER values (MODEL.md). TS reads these and applies`)
	fmt.Fprintln(w, `// them to GPU materials / bakes the env map from them — no shading values of its`)
	fmt.Fprintln(w, `// own. The GPU machinery (three.js materials, PMREM bake, binding) stays in TS.`)
	fmt.Fprintln(w)
	for _, p := range params {
		if p.isStr {
			fmt.Fprintf(w, "export const %s = %q;\n", p.tsName, p.value)
		} else {
			fmt.Fprintf(w, "export const %s = %s;\n", p.tsName, p.value)
		}
	}

	w.Flush()
	return os.WriteFile(outPath, buf.Bytes(), 0644)
}
