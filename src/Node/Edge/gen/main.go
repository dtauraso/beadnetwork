package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/scripts/genpaths"
	edge "github.com/dtauraso/wirefold/src/Node/Edge"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(edge.ValueRelTemplate), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by src/Node/Edge/gen from EdgeValueNames in edge_values.go —\n")
	b.WriteString("// do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// One block file per edge, written by the source node's goroutine. The row\n")
	b.WriteString("// sits in the path, not in the file, so no writer touches another edge's bytes.\n\n")
	b.WriteString("export const EDGE_VALUE_NAMES = [\n")
	for _, name := range edge.EdgeValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type EdgeValueName = (typeof EDGE_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genpaths.Name = "Node/Edge/gen"
	_, srcRoot := genpaths.Roots()

	dir := filepath.Join(srcRoot, "Node", "Edge")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		genpaths.Fatalf("write edge paths: %v", err)
	}
	genpaths.Announce(pathsDir, 1, "edge block path template")

	namesPath := filepath.Join(dir, "edge-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(edge.EdgeValueNames), "edge values")
}
