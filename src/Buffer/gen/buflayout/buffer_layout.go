func isSingletonBlock(name string) bool {
	return name == "Camera" || name == "RuleBuilder" || name == "Scene"
}

var movedToColumns = map[string]bool{
	"Scene":         true,
	"Panel":         true,
	"Overlay":       true,
	"Camera":        true,
	"Edge":          true,
	"Node":          true,
	"Interior":      true,
	"EdgeBead":      true,
	"SpeedPanel":    true,
	"TiltArrow":     true,
	"ChannelVector": true,
	"PointerTarget": true,
}

func hasRow(name string) bool { return !movedToColumns[name] }

func WriteBufferLayoutGo(headerPath, rowsPathA, rowsPathB, singletonsPath string, schema BufLayoutSchema) error {
	fp := buildBufFingerprint(schema)

	if err := writeBufferLayoutGoHeader(headerPath, schema, fp); err != nil {
		return err
	}
	if err := writeBufferLayoutGoRows(rowsPathA, rowsPathB, schema, fp); err != nil {
		return err
	}
	if err := writeBufferLayoutGoSingletons(singletonsPath, schema, fp); err != nil {
		return err
	}
	return nil
}

func writeBufferLayoutGoPreamble(w *bufio.Writer, fp string) {
	writeBufferLayoutGoPreambleFor(w, fp, true, true)
}

func writeBufferLayoutGoPreambleFor(w *bufio.Writer, fp string, needsBinary, needsMath bool) {
	fmt.Fprintln(w, `// GENERATED by src/Buffer/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/Buffer/layout_version.go  Regenerate: go generate ./...`)
	fmt.Fprintf(w, "// BUF_LAYOUT_FINGERPRINT: %s\n", fp)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `package bufferlayout`)
	fmt.Fprintln(w)
	if !needsBinary && !needsMath {
		return
	}
	fmt.Fprintln(w, `import (`)
	if needsBinary {
		fmt.Fprintln(w, `	"encoding/binary"`)
	}
	if needsMath {
		fmt.Fprintln(w, `	"math"`)
	}
	fmt.Fprintln(w, `)`)
	fmt.Fprintln(w)
}

func writeBufferLayoutGoHeaderPreamble(w *bufio.Writer, fp string) {
	fmt.Fprintln(w, `// GENERATED by src/Buffer/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/Buffer/layout_version.go  Regenerate: go generate ./...`)
	fmt.Fprintf(w, "// BUF_LAYOUT_FINGERPRINT: %s\n", fp)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `package bufferlayout`)
	fmt.Fprintln(w)
}

func writeBufferLayoutGoHeader(outPath string, schema BufLayoutSchema, fp string) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)
	writeBufferLayoutGoHeaderPreamble(w, fp)

	fmt.Fprintf(w, "// BufLayoutVersionGenerated must equal BufLayoutVersion in layout.go.\n")
	fmt.Fprintf(w, "const BufLayoutVersionGenerated = %d\n", schema.version)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// BufLayoutFingerprintHash is FNV-1a over BUF_LAYOUT_FINGERPRINT above. It rides in`)
	fmt.Fprintln(w, `// every VIEW frame header so the decoder can REFUSE a frame whose layout it was not`)
	fmt.Fprintln(w, `// built for, instead of reading the bytes into the wrong columns and drawing garbage.`)
	fmt.Fprintln(w, `//`)
	fmt.Fprintln(w, `// It is DERIVED, never hand-written: any column added, removed, resized or reordered`)
	fmt.Fprintln(w, `// changes the fingerprint and therefore this value. BufLayoutVersion is a human intent`)
	fmt.Fprintln(w, `// marker and is NOT what the wire check uses — a forgotten bump must not be able to`)
	fmt.Fprintln(w, `// make a skewed layout look compatible.`)
	fmt.Fprintf(w, "const BufLayoutFingerprintHash uint32 = %d\n", fnv1aHash(fp))
	fmt.Fprintln(w)
	fmt.Fprintf(w, "// BufInteriorSlotsPerNodeGenerated must equal BufInteriorSlotsPerNode in layout.go.\n")
	fmt.Fprintf(w, "const BufInteriorSlotsPerNodeGenerated = %d\n", schema.interiorSlotsPerNode)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// BufHeaderSize is the byte width of the retired combined-snapshot frame's header.`)
	fmt.Fprintln(w, `// The combined SCENE/BEAD/NODE/EDGE frame is gone entirely — each goroutine now streams`)
	fmt.Fprintln(w, `// its own per-owner frame (VIEW/EDGE_STREAM/NODE_STREAM/INTERIOR_STREAM — see`)
	fmt.Fprintln(w, `// Buffer/frame_tags.go and memory/feedback/architecture/bridge/feedback_no_single_writer_bridge.md); this constant`)
	fmt.Fprintln(w, `// is a historical layout marker, not consumed by any live decoder:`)
	fmt.Fprintln(w, `// [tick:u32][layoutLinkCount:u32]`)
	fmt.Fprintln(w, `const BufHeaderSize = 8`)

	w.Flush()
	return formatAndWrite(buf, outPath)
}

func formatAndWrite(buf bytes.Buffer, outPath string) error {
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w\n--- unformatted ---\n%s", outPath, err, buf.String())
	}
	return os.WriteFile(outPath, formatted, 0644)
}
