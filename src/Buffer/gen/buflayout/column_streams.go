package buflayout

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

var perNodeStreamBlocks = []string{"Node", "Interior", "EdgeBead", "TiltArrow", "ChannelVector"}

var perEdgeStreamBlocks = []string{"Edge"}

var singletonStreamBlocks = []string{"Camera", "Scene", "NodeRingPoint", "BeadRingPoint", "SpeedPanel", "TiltPanel", "AnglePill", "OverlaysPill", "FitChip", "TabStrip", "PointerTarget"}

func (s BufLayoutSchema) columnsOf(name string) int {
	for _, b := range s.Blocks {
		if b.name == name {
			return len(b.columns)
		}
	}
	return 0
}

func (s BufLayoutSchema) colStreamGroups() (perNode, perEdge, singleton []string) {
	return perNodeStreamBlocks, perEdgeStreamBlocks, singletonStreamBlocks
}

func WriteColumnStreamsGo(path string, schema BufLayoutSchema) error {
	perNode, perEdge, singleton := schema.colStreamGroups()

	var b strings.Builder
	b.WriteString("package bufferlayout\n\n")
	b.WriteString("// GENERATED by src/Buffer/gen. Do not edit.\n\n")

	b.WriteString("// ColumnsPerNodeStream is how many column channels one node owns.\n")
	b.WriteString("const ColumnsPerNodeStream = ")
	total := 0
	for _, n := range perNode {
		total += schema.columnsOf(n)
	}
	fmt.Fprintf(&b, "%d\n\n", total)

	b.WriteString("const ColumnsPerEdgeStream = ")
	totalEdge := 0
	for _, n := range perEdge {
		totalEdge += schema.columnsOf(n)
	}
	fmt.Fprintf(&b, "%d\n\n", totalEdge)

	b.WriteString("const ColumnsInSingletonStreams = ")
	totalSingle := 0
	for _, n := range singleton {
		totalSingle += schema.columnsOf(n)
	}
	fmt.Fprintf(&b, "%d\n\n", totalSingle)

	b.WriteString("// ColumnStreamCount is every column channel a scene of this size needs.\n")
	b.WriteString("func ColumnStreamCount(nodes, edges int) int {\n")
	b.WriteString("\treturn nodes*ColumnsPerNodeStream + edges*ColumnsPerEdgeStream + ColumnsInSingletonStreams\n}\n\n")

	for _, name := range append(append([]string{}, perNode...), append(perEdge, singleton...)...) {
		fmt.Fprintf(&b, "const ColStreamBase%s = %d\n", name, schema.colStreamBaseOf(name))
	}
	b.WriteString("\n")

	for _, blk := range schema.Blocks {
		if !isColumnStreamBlock(blk.name) {
			continue
		}
		for i, c := range blk.columns {
			fmt.Fprintf(&b, "const ColStream%s%s = ColStreamBase%s + %d\n", blk.name, c.name, blk.name, i)
		}
	}

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func (s BufLayoutSchema) colStreamBaseOf(name string) int {
	base := 0
	for _, group := range [][]string{perNodeStreamBlocks, perEdgeStreamBlocks, singletonStreamBlocks} {
		base = 0
		found := false
		for _, n := range group {
			if n == name {
				found = true
				break
			}
			base += s.columnsOf(n)
		}
		if found {
			return base
		}
	}
	return 0
}

func WriteColumnStreamsTS(path string, schema BufLayoutSchema) error {
	perNode, perEdge, singleton := schema.colStreamGroups()

	var b strings.Builder
	b.WriteString("// GENERATED by src/Buffer/gen. Do not edit.\n\n")

	total, totalEdge, totalSingle := 0, 0, 0
	for _, n := range perNode {
		total += schema.columnsOf(n)
	}
	for _, n := range perEdge {
		totalEdge += schema.columnsOf(n)
	}
	for _, n := range singleton {
		totalSingle += schema.columnsOf(n)
	}

	fmt.Fprintf(&b, "export const COLUMNS_PER_NODE_STREAM = %d;\n", total)
	fmt.Fprintf(&b, "export const COLUMNS_PER_EDGE_STREAM = %d;\n", totalEdge)
	fmt.Fprintf(&b, "export const COLUMNS_IN_SINGLETON_STREAMS = %d;\n\n", totalSingle)

	b.WriteString("export function columnStreamCount(nodes: number, edges: number): number {\n")
	b.WriteString("  return nodes * COLUMNS_PER_NODE_STREAM + edges * COLUMNS_PER_EDGE_STREAM + COLUMNS_IN_SINGLETON_STREAMS;\n}\n\n")

	for _, name := range append(append([]string{}, perNode...), append(perEdge, singleton...)...) {
		fmt.Fprintf(&b, "export const COL_STREAM_BASE_%s = %d;\n", camelToScreamingSnake(name), schema.colStreamBaseOf(name))
	}
	b.WriteString("\n")

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func WriteBlockColumnsTS(schema BufLayoutSchema, basePath string) ([]string, error) {
	rel := func(from, to string) string {
		r, err := filepath.Rel(from, to)
		if err != nil {
			return to
		}
		if !strings.HasPrefix(r, ".") {
			r = "./" + r
		}
		return r
	}

	byDir := map[string][]bufBlock{}
	var dirs []string
	for _, blk := range schema.Blocks {
		if !isColumnStreamBlock(blk.name) || blk.dir == "" {
			continue
		}
		if _, seen := byDir[blk.dir]; !seen {
			dirs = append(dirs, blk.dir)
		}
		byDir[blk.dir] = append(byDir[blk.dir], blk)
	}

	var written []string
	for _, dir := range dirs {
		blocks := byDir[dir]

		var names []string
		var body strings.Builder
		for _, blk := range blocks {
			screaming := camelToScreamingSnake(blk.name)
			names = append(names, blk.name)
			body.WriteString("\n")
			for i, c := range blk.columns {
				fmt.Fprintf(&body, "export const COL_STREAM_%s_%s = COL_STREAM_BASE_%s + %d;\n",
					screaming, camelToScreamingSnake(c.name), screaming, i)
			}
		}

		var b strings.Builder
		b.WriteString("// GENERATED by src/Buffer/gen. Do not edit.\n")
		fmt.Fprintf(&b, "// Source: the %s block(s) in this directory.\n\n", strings.Join(names, ", "))
		b.WriteString("import {\n")
		for _, blk := range blocks {
			fmt.Fprintf(&b, "  COL_STREAM_BASE_%s,\n", camelToScreamingSnake(blk.name))
		}
		fmt.Fprintf(&b, "} from %q;\n", strings.TrimSuffix(rel(dir, basePath), ".ts"))
		b.WriteString(body.String())

		out := filepath.Join(dir, "columns-gen.ts")
		if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
			return nil, err
		}
		written = append(written, out)
	}
	return written, nil
}

func isColumnStreamBlock(name string) bool {
	for _, group := range [][]string{perNodeStreamBlocks, perEdgeStreamBlocks, singletonStreamBlocks} {
		for _, n := range group {
			if n == name {
				return true
			}
		}
	}
	return false
}
