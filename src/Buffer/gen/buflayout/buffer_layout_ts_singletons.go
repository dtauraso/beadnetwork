package buflayout

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
)

func writeBufferLayoutTSSingletons(outPath string, schema BufLayoutSchema) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by src/Buffer/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: src/Buffer/layout_version.go  Regenerate: go generate ./...`)
	fmt.Fprintln(w)

	fmt.Fprintln(w, `export {};`)
	fmt.Fprintln(w)

	for _, blk := range schema.Blocks {
		if !isSingletonBlock(blk.name) || !hasRow(blk.name) {
			continue
		}
		writeTSBlockConstsAndReaders(w, blk, true)
	}

	w.Flush()
	return os.WriteFile(outPath, buf.Bytes(), 0644)
}
