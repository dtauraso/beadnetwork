package nodedefs

import (
	"bufio"
	"bytes"
	"fmt"
	"os"

	"github.com/dtauraso/wirefold/scripts/kindscan"
)

func WriteNodeDefs(outPath string, kinds []kindscan.KindEntry) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by src/NodeKinds/gen — do not edit. Source: src/NodeKinds/<Kind>/node.go + SPEC.md`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `export interface NodeDef {`)
	fmt.Fprintln(w, `  bg: string;`)
	fmt.Fprintln(w, `  border: string;`)
	fmt.Fprintln(w, `  text: string;`)
	fmt.Fprintln(w, `  minWidth?: number;`)
	fmt.Fprintln(w, `  // NodeTypeDef-compatible fields for schema/adapter consumers.`)
	fmt.Fprintln(w, `  shape?: string;`)
	fmt.Fprintln(w, `  fill?: string;`)
	fmt.Fprintln(w, `  stroke?: string;`)
	fmt.Fprintln(w, `  width?: number;`)
	fmt.Fprintln(w, `  height?: number;`)
	fmt.Fprintln(w, `  // One line saying what this kind IS, from its SPEC.md "## Description" section.`)
	fmt.Fprintln(w, `  // The node palette shows it under the kind's name; absent when the SPEC has no such`)
	fmt.Fprintln(w, `  // section, which renders as no description rather than as a placeholder.`)
	fmt.Fprintln(w, `  desc?: string;`)
	fmt.Fprintln(w, `  inputs?: { name: string; kind: string; isMulti?: boolean }[];`)
	fmt.Fprintln(w, `  outputs?: { name: string; kind: string; isMulti?: boolean }[];`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)

	fmt.Fprintln(w, `// PascalCase Go kind names that have a Go runtime.`)
	fmt.Fprintln(w, `// Single source of truth — derived from bead.Register calls.`)
	fmt.Fprintf(w, "export const RUNTIME_IMPLEMENTED_KINDS: ReadonlySet<string> = new Set([\n")
	for _, e := range kinds {
		fmt.Fprintf(w, "  %q,\n", e.GoKind)
	}
	fmt.Fprintln(w, `]);`)
	fmt.Fprintln(w)

	type kindDef struct {
		goKind string
		kindID uint8
		def    string
	}
	defs := make([]kindDef, len(kinds))
	for i, e := range kinds {
		defs[i] = kindDef{goKind: e.GoKind, kindID: e.KindID, def: buildDef(e.View, e.Ports)}
	}
	fmt.Fprintln(w, `export const NODE_DEFS: Record<string, NodeDef> = {`)
	for _, kd := range defs {
		fmt.Fprintf(w, "  %s: %s,\n", kd.goKind, kd.def)
	}
	fmt.Fprint(w, `};`, "\n")
	fmt.Fprintln(w)

	maxID := -1
	byID := map[uint8]kindDef{}
	for _, kd := range defs {
		byID[kd.kindID] = kd
		if int(kd.kindID) > maxID {
			maxID = int(kd.kindID)
		}
	}
	hasGap := len(byID) <= maxID
	arrayType := "readonly NodeDef[]"
	namesType := "readonly string[]"
	if hasGap {

		arrayType = "readonly (NodeDef | undefined)[]"
		namesType = "readonly (string | undefined)[]"
	}
	fmt.Fprintf(w, "export const NODE_DEFS_ARRAY: %s = [\n", arrayType)
	for id := 0; id <= maxID; id++ {
		if kd, ok := byID[uint8(id)]; ok {
			fmt.Fprintf(w, "  %s,\n", kd.def)
		} else {
			fmt.Fprintf(w, "  undefined, // gap left by a removed kind (KindId %d)\n", id)
		}
	}
	fmt.Fprintln(w, `];`)
	fmt.Fprintln(w)

	fmt.Fprintf(w, "export const NODE_KIND_NAMES: %s = [\n", namesType)
	for id := 0; id <= maxID; id++ {
		if kd, ok := byID[uint8(id)]; ok {
			fmt.Fprintf(w, "  %q,\n", kd.goKind)
		} else {
			fmt.Fprintf(w, "  undefined, // gap left by a removed kind (KindId %d)\n", id)
		}
	}
	fmt.Fprintln(w, `];`)

	w.Flush()
	return os.WriteFile(outPath, buf.Bytes(), 0644)
}
