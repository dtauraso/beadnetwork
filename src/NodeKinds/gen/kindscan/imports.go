package kindscan

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
)

func WriteKindImports(outPath, networkPkg string, kinds []KindEntry) error {
	dirs := make([]string, 0, len(kinds))
	for _, k := range kinds {
		dirs = append(dirs, k.Dir)
	}
	sort.Strings(dirs)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by src/NodeKinds/gen. DO NOT EDIT.\n\n")
	buf.WriteString("// Importing this package is what makes every kind exist in the binary: each\n")
	buf.WriteString("// blank import below runs that kind's init(), which is what registers it. A\n")
	buf.WriteString("// kind missing from here compiles, has its SPEC.md and its NODE_DEFS entry,\n")
	buf.WriteString("// and fails at runtime with unknown type.\n")
	buf.WriteString("package NodeKinds\n\nimport (\n")
	for _, d := range dirs {
		fmt.Fprintf(&buf, "\t_ %q\n", networkPkg+"/"+d)
	}
	buf.WriteString(")\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0644)
}
