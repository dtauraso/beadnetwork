package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	Panels "github.com/dtauraso/wirefold/Chrome/Panels"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(Panels.ValueRelPath), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Chrome/Panels/gen from PointerTargetValueNames in\n")
	b.WriteString("// pointer_target_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The pointer target follows the cursor, so this one block file is read per\n")
	b.WriteString("// frame rather than on the interval the rest of chrome uses.\n\n")
	b.WriteString("export const POINTER_TARGET_VALUE_NAMES = [\n")
	for _, name := range Panels.PointerTargetValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type PointerTargetValueName = (typeof POINTER_TARGET_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genName = "Panels/gen"
	_, srcRoot := roots()

	dir := filepath.Join(srcRoot, "Chrome", "Panels")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		fatalf("write pointer target paths: %v", err)
	}
	announce(pathsDir, 1, "pointer target block path")

	namesPath := filepath.Join(dir, "pointer-target-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		fatalf("write %s: %v", namesPath, err)
	}
	announce(namesPath, len(Panels.PointerTargetValueNames), "pointer target values")
}
