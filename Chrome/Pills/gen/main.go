package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Chrome/Pills"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(Pills.ValueRelPath()), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Chrome/Pills/gen from PillValueNames in pill_values.go —\n")
	b.WriteString("// do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The overlays popover's values, in the order they sit in the block. The\n")
	b.WriteString("// renderer learns where that block is from Chrome/Pills/paths/, which Go\n")
	b.WriteString("// writes from this same list, so neither side spells a path.\n\n")
	b.WriteString("export const OVERLAYS_PILL_VALUE_NAMES = [\n")
	for _, name := range Pills.PillValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type OverlaysPillValueName = (typeof OVERLAYS_PILL_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genName = "Pills/gen"
	_, srcRoot := roots()

	dir := filepath.Join(srcRoot, "Chrome", "Pills")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		fatalf("write overlays pill paths: %v", err)
	}
	announce(pathsDir, 1, "overlays pill block path")

	namesPath := filepath.Join(dir, "pill-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		fatalf("write %s: %v", namesPath, err)
	}
	announce(namesPath, len(Pills.PillValueNames), "overlays pill values")
}
