#!/usr/bin/env bash

# PLACEMENT: none | universal prose hygiene: comments are removed everywhere, not in one place
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

APPLY=0
if [ "${1:-}" = "--apply" ]; then APPLY=1; shift; fi

readonly KEEP='go:generate|nolint|lint:ignore|eslint-|@ts-|prettier-|tslint:|@type|@param|@returns|PLACEMENT:|generated by|GENERATED by|@generated|DO NOT EDIT|Regenerate:|FINGERPRINT|Source:|Copyright|SPDX|LICEN[SC]E|[0-9]{4}-[0-9]{2}-[0-9]{2}|path-resolution-ok|deliberate:|allowlist'

readonly FENCE_START='^[[:space:]]*//[[:space:]]*[A-Z0-9_]+_START[[:space:]]*$'
readonly FENCE_END='^[[:space:]]*//[[:space:]]*[A-Z0-9_]+_END[[:space:]]*$'

readonly STRIP_BLOCKS='
  function flush(keep,   i) {
    if (emit) for (i = 1; i <= n; i++) if (keep) print buf[i]
    if (!keep) removed += n
    n = 0
  }
  $0 ~ fenceStart { fenced = 1 }
  /^[[:space:]]*\/\// {
    buf[++n] = $0
    if (fenced || $0 ~ keep) blockKeep = 1
    if ($0 ~ fenceEnd) fenced = 0
    next
  }
  {
    if (n) { flush(blockKeep); dropped = !blockKeep; blockKeep = 0 }
    if (dropped && $0 ~ /^[[:space:]]*$/) { dropped = 0; next }
    dropped = 0
    if (emit) print
  }
  END { if (n) flush(blockKeep); if (!emit) print removed + 0 }
'

files=()
while IFS= read -r f; do
  case "$f" in */node_modules/*) continue ;; *.go|*.ts|*.tsx) ;; *) continue ;; esac
  [ -f "$f" ] || continue
  head -3 "$f" 2>/dev/null | grep -qiE 'generated by|@generated' && continue
  files+=("$f")
done < <(if [ "$#" -gt 0 ]; then printf "%s\n" "$@"; else git ls-files "*.go" "*.ts" "*.tsx"; fi)

if [ "${#files[@]}" -eq 0 ]; then echo "strip-comments: no source files to scan"; exit 0; fi

total=0
for f in "${files[@]}"; do
  n="$(awk -v keep="$KEEP" -v fenceStart="$FENCE_START" -v fenceEnd="$FENCE_END" -v emit=0 "$STRIP_BLOCKS" "$f")"
  [ "$n" -eq 0 ] && continue
  total=$((total + n))
  if [ "$APPLY" -eq 1 ]; then
    awk -v keep="$KEEP" -v fenceStart="$FENCE_START" -v fenceEnd="$FENCE_END" -v emit=1 "$STRIP_BLOCKS" "$f" > "$f.stripped" && mv "$f.stripped" "$f"
  else
    printf '%6d  %s\n' "$n" "$f"
  fi
done

if [ "$APPLY" -eq 1 ]; then
  echo "strip-comments: removed $total comment line(s) from ${#files[@]} file(s)"
else
  echo "strip-comments: $total comment line(s) in ${#files[@]} file(s) would be removed (--apply to do it)"
fi
