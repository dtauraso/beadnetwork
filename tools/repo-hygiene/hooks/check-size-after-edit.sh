#!/usr/bin/env bash
set -uo pipefail

# PLACEMENT: none | PostToolUse hook wrapper; it measures the file just written, it does not constrain a source path

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"

payload="$(cat)"

printf '%s' "$payload" | REPO_ROOT="$REPO_ROOT" python3 -c '
import json, os, re, sys

FILE_CEILING = 200
DIR_CEILING = 20
SCANNED_EXT = (".go", ".ts", ".tsx", ".js", ".md", ".html", ".css", ".sh", ".py")
GEN_MARK = re.compile(r"DO NOT EDIT|Code generated|@generated|GENERATED by", re.I)

try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(0)

path = (d.get("tool_input", {}) or {}).get("file_path", "") or ""
if not path:
    sys.exit(0)

root = os.environ.get("REPO_ROOT", "")
if root:
    os.chdir(root)
try:
    rel = os.path.relpath(path, root or ".")
except ValueError:
    sys.exit(0)
if rel.startswith("..") or "node_modules" in rel or "/out/" in rel:
    sys.exit(0)
if not rel.endswith(SCANNED_EXT) or not os.path.isfile(rel):
    sys.exit(0)

def is_generated(p):
    base = os.path.basename(p)
    if "_gen." in base or "-gen." in base:
        return True
    try:
        head = "".join(open(p, encoding="utf-8", errors="replace").readlines()[:3])
    except OSError:
        return False
    return bool(GEN_MARK.search(head))

if is_generated(rel):
    sys.exit(0)

def code_lines(p):
    n = 0
    try:
        for line in open(p, encoding="utf-8", errors="replace"):
            s = line.strip()
            if not s or s.startswith("//") or s.startswith("/*") or s.startswith("*"):
                continue
            n += 1
    except OSError:
        return 0
    return n

def head_code_lines(p):
    import subprocess
    r = subprocess.run(["git", "show", f"HEAD:{p}"], capture_output=True, text=True)
    if r.returncode != 0:
        return 0
    n = 0
    for line in r.stdout.split("\n"):
        s = line.strip()
        if not s or s.startswith("//") or s.startswith("/*") or s.startswith("*"):
            continue
        n += 1
    return n

msgs = []

n = code_lines(rel)
if n > FILE_CEILING and head_code_lines(rel) <= FILE_CEILING:
    msgs.append(
        f"{rel} just crossed the ceiling: {n} code lines, was under {FILE_CEILING} at HEAD.\n"
        "Split it NOW, before moving on. Ask what the sequential phases are, not only what is "
        "pure — a short orchestrator over named impure phases is the target shape. If it genuinely "
        "cannot be split, add it to ALLOWED in tools/repo-hygiene/size/check-file-size.sh with a "
        "mechanism a compiler, parser, generator or stated rule enforces. Not: cohesive, one "
        "concern, no seam, already small, hot path, entry point, impure."
    )

d_ = os.path.dirname(rel) or "."
count = 0
try:
    for f in os.listdir(d_):
        p = os.path.join(d_, f)
        if os.path.isfile(p) and p.endswith(SCANNED_EXT) and not is_generated(p):
            count += 1
except OSError:
    count = 0

ALLOWED_DIRS = {
    "tools/gen-node-defs/kindscan", "tools/gen-node-defs/buflayout",
    "nodes/Wiring/nodeactor/owners", "tools", "nodes/PairNode", ".",
}
if count > DIR_CEILING and d_ not in ALLOWED_DIRS:
    msgs.append(
        f"{d_} now holds {count} hand-edited files at its top level, over the {DIR_CEILING} "
        "ceiling.\nCluster it by concern NOW. Derive the grouping from what the files do, not "
        "from filename prefixes. Note the count is a prompt to look, not a verdict — a directory "
        "can grow because an object was correctly decomposed. If it should stay flat, add it to "
        "ALLOWED in tools/repo-hygiene/size/check-dir-size.sh with an enforced mechanism."
    )

if not msgs:
    sys.exit(0)

print(json.dumps({
    "hookSpecificOutput": {
        "hookEventName": "PostToolUse",
        "additionalContext": "SIZE CEILING CROSSED — fix before continuing.\n\n" + "\n\n".join(msgs),
    }
}))
' 2>/dev/null || true

exit 0
