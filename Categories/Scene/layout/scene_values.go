package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/beadnetwork/scripts/genpaths"

	"github.com/dtauraso/beadnetwork/Categories/Scene"
)

func writeValuePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, v := range Scene.SceneValues {
		name := v.Name + ".bin"
		keep[name] = true
		if err := genpaths.WriteIfChanged(filepath.Join(pathsDir, name), []byte(v.Path), 0o644); err != nil {
			return err
		}
	}

	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || keep[e.Name()] { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeValueNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Scene/values from SceneValues in Categories/Scene/scene_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The scene values the renderer reads as files, and how wide each one is on\n")
	b.WriteString("// disk. valuefile writes every leaf as eight little-endian bytes, so the kind\n")
	b.WriteString("// says how to read them, not how many.\n\n")
	b.WriteString("export type SceneValueKind = \"f64\" | \"i64\";\n\n")
	b.WriteString("export interface SceneValueDef {\n  name: string;\n  kind: SceneValueKind;\n}\n\n")
	b.WriteString("export const SCENE_VALUES: SceneValueDef[] = [\n")
	for _, v := range Scene.SceneValues {
		fmt.Fprintf(&b, "  { name: %q, kind: %q },\n", v.Name, v.Kind)
	}
	b.WriteString("];\n")
	return genpaths.WriteIfChanged(path, []byte(b.String()), 0o644)
}
