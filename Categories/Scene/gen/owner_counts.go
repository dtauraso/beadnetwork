package main

import (
	"github.com/dtauraso/wirefold/scripts/genpaths"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	Scene "github.com/dtauraso/wirefold/Categories/Scene"
)

func writeOwnerCountsPathFile(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(Scene.CountsValueRelPath), 0o644)
}

func writeOwnerCountsNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Scene/gen from CountsValueNames in\n")
	b.WriteString("// owner_counts_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// How many nodes and edges the scene has, which is what every renderer loop\n")
	b.WriteString("// over owners counts up to.\n\n")
	b.WriteString("export const OWNER_COUNTS_VALUE_NAMES = [\n")
	for _, name := range Scene.CountsValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type OwnerCountsValueName = (typeof OWNER_COUNTS_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func generateOwnerCounts(srcRoot string) {
	dir := filepath.Join(srcRoot, "Scene")
	pathsDir := filepath.Join(dir, "owner-counts-paths")
	if err := writeOwnerCountsPathFile(pathsDir); err != nil {
		genpaths.Fatalf("write owner counts paths: %v", err)
	}
	genpaths.Announce(pathsDir, 1, "owner counts block path")

	namesPath := filepath.Join(dir, "owner-counts-values-gen.ts")
	if err := writeOwnerCountsNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(Scene.CountsValueNames), "owner counts values")
}
