package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/beadnetwork/scripts/genpaths"

	"github.com/dtauraso/beadnetwork/Categories/Scene/Preview"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := genpaths.WriteIfChanged(filepath.Join(pathsDir, "block.bin"), []byte(Preview.ValueRelPath()), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Scene/Preview/layout from PreviewValueNames in preview_values.go —\n")
	b.WriteString("// do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The Links preview values: the hovered link's edge and the ghost places. The renderer\n")
	b.WriteString("// learns where from Categories/Scene/Preview/paths/, which Go writes from this same list,\n")
	b.WriteString("// so neither side spells a path.\n\n")
	b.WriteString("export const PREVIEW_VALUE_NAMES = [\n")
	for _, name := range Preview.PreviewValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type PreviewValueName = (typeof PREVIEW_VALUE_NAMES)[number];\n")
	return genpaths.WriteIfChanged(path, []byte(b.String()), 0o644)
}

func main() {
	genpaths.SetName("Categories/Scene/Preview/layout")
	_, srcRoot := genpaths.Roots()

	dir := filepath.Join(srcRoot, "Scene", "Preview")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		genpaths.Fatalf("write preview paths: %v", err)
	}
	genpaths.Announce(pathsDir, len(Preview.PreviewValueNames), "preview paths")

	namesPath := filepath.Join(dir, "preview-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(Preview.PreviewValueNames), "preview values")
}
