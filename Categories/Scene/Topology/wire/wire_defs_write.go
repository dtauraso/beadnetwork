package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"sort"
	"strings"
)

func WriteWireDefs(outPath string, props []wireProp) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by: go generate ./... (regenerate after editing wire:"..." tags in Categories/Scene/Topology/topo_spec.go)`)
	fmt.Fprintln(w, `// Source: Categories/Scene/Topology/topo_spec.go wire:"prop,..." tags. Do not edit by hand.`)
	fmt.Fprintln(w)

	primitives := map[string]bool{"string": true, "number": true, "boolean": true}
	seen := map[string]bool{}
	var nonPrim []string
	for _, p := range props {
		t := p.tsType
		if primitives[t] || seen[t] {
			continue
		}
		seen[t] = true
		nonPrim = append(nonPrim, t)
	}
	sort.Strings(nonPrim)
	if len(nonPrim) > 0 {
		fmt.Fprintf(w, "import type { %s } from \"./types\";\n", strings.Join(nonPrim, ", "))
		fmt.Fprintln(w)
	}
	fmt.Fprintln(w, `export interface WirePropDef {`)
	fmt.Fprintln(w, `  tsType: string;`)
	fmt.Fprintln(w, `  required: boolean;`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `export const WIRE_PROPS: Record<string, WirePropDef> = {`)
	for _, p := range props {
		req := "false"
		if p.required {
			req = "true"
		}
		fmt.Fprintf(w, "  %-12s { tsType: %-12s required: %s },\n",
			p.propName+":", `"`+p.tsType+`",`, req)
	}
	fmt.Fprintln(w, `};`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// Derived from WIRE_PROPS — do not hand-edit. Consumed by Edge and EdgeData.`)
	fmt.Fprintln(w, `export type WireProps = {`)
	for _, p := range props {
		opt := "?"
		if p.required {
			opt = ""
		}
		fmt.Fprintf(w, "  %s%s: %s;\n", p.propName, opt, p.tsType)
	}
	fmt.Fprintln(w, `};`)

	w.Flush()
	return os.WriteFile(outPath, buf.Bytes(), 0644)
}
