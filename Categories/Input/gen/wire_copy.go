package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var wireTargets = []struct {
	dir   string
	pkg   string
	lists []string // fingerprint markers this concern reads
	kinds []string // record kind constants it names
	enum  bool     // needs EnumAt
}{
	{dir: "Categories/Input/Drag", pkg: "Drag", enum: true,
		kinds: []string{"raw-input"}},
	{dir: "Categories/Input/Stdin", pkg: "Stdin", enum: true,
		lists: []string{"updateKinds="}, kinds: []string{"save", "raw-input", "edit-update"}},
}

var listVarName = map[string]string{
	"updateKinds=":  "InUpdateKinds",
}

var kindConstName = map[string]string{
	"save":        "InKindSave",
	"raw-input":   "InKindRawInput",
	"edit-update": "InKindEditUpdate",
}

type wireSource interface {
	List(marker string) []string
	KindValue(name string) string
}

func copyWireVocabulary(repoRoot string, fp wireSource) {
	for _, t := range wireTargets {
		var b strings.Builder
		fmt.Fprintln(&b, "// GENERATED by Categories/Input/gen — do not edit.")
		fmt.Fprintln(&b, "// Source: the input layout declared in Categories/Input/gen.")
		fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
		fmt.Fprintln(&b)
		fmt.Fprintf(&b, "package %s\n\n", t.pkg)

		if len(t.kinds) > 0 {
			fmt.Fprintln(&b, "const (")
			for _, k := range t.kinds {
				fmt.Fprintf(&b, "\t%s = %s\n", kindConstName[k], fp.KindValue(k))
			}
			fmt.Fprintln(&b, ")")
			fmt.Fprintln(&b)
		}

		lists := append([]string{}, t.lists...)
		sort.Strings(lists)
		for _, m := range lists {
			fmt.Fprintf(&b, "var %s = []string{", listVarName[m])
			for i, v := range fp.List(m) {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", v)
			}
			fmt.Fprintln(&b, "}")
			fmt.Fprintln(&b)
		}

		if t.enum {
			fmt.Fprintln(&b, `func enumAt(list []string, i byte) string {
	if int(i) >= len(list) {
		return ""
	}
	return list[i]
}`)
		}

		outPath := filepath.Join(repoRoot, filepath.FromSlash(t.dir), "wire_gen.go")
		src, ferr := format.Source([]byte(b.String()))
		if ferr != nil {
			fatalf("format %s: %v", outPath, ferr)
		}
		if err := os.WriteFile(outPath, src, 0o644); err != nil {
			fatalf("write %s: %v", outPath, err)
		}
		announce(outPath, len(lists)+len(t.kinds), fmt.Sprintf("wire vocabulary for %s", t.pkg))
	}
}
