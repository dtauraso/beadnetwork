package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

var targets = []struct {
	dir string
	pkg string
}{
	{"Categories/Node", "Node"},
	{"Categories/Node/Edge", "edge"},
	{"Categories/Scene", "Scene"},
	{"Categories/Overlay", "Overlay"},
	{"Categories/Chrome/Panels/Panel", "Panel"},
	{"Categories/Speed", "Speed"},
	{"Categories/Input/Drag", "Drag"},
}

func copyRecordReaders(repoRoot string) {
	srcPath := filepath.Join(repoRoot, "Categories", "Input", "gen", "record_reader_template.go")
	raw, err := os.ReadFile(srcPath)
	if err != nil {
		fatalf("read %s: %v", srcPath, err)
	}
	body := string(raw)
	if !strings.HasPrefix(body, "package main\n") {
		fatalf("%s does not start with 'package main'; the copier reads it verbatim "+
			"and only rewrites that line, so an unexpected shape would emit something wrong", srcPath)
	}
	body = strings.TrimPrefix(body, "package main\n")

	for _, t := range targets {
		out := "// GENERATED by Categories/Input/gen — do not edit.\n" +
			"// Source: Categories/Input/gen/record_reader_template.go, copied verbatim.\n" +
			"// Regenerate with: go generate ./...\n\n" +
			"package " + t.pkg + "\n" + body
		outPath := filepath.Join(repoRoot, filepath.FromSlash(t.dir), "record_reader_gen.go")
		if err := os.WriteFile(outPath, []byte(out), 0o644); err != nil {
			fatalf("write %s: %v", outPath, err)
		}
		announce(outPath, 1, fmt.Sprintf("record reader for %s", t.pkg))
	}
}
