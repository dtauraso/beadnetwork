package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/Input/Drag"
)

func main() {
	genName = "Categories/Input/Drag/gen"
	_, srcRoot := roots()

	var b strings.Builder
	fmt.Fprintln(&b, "// GENERATED by Categories/Input/Drag/gen — do not edit.")
	fmt.Fprintln(&b, "// Source: Drag's kinds.go and Stdin's record_kinds.go.")
	fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "export const IN_KIND_RAW_INPUT = %d;\n\n", Drag.KindRawInput)
	writeWireList(&b, "IN_EVENT_KINDS", Drag.EventKinds)
	fmt.Fprintln(&b)
	writeWireList(&b, "IN_HIT_KINDS", Drag.HitKinds)
	fmt.Fprintln(&b)

	outPath := filepath.Join(srcRoot, "Input", "Drag", "wire-gen.ts")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}
	announce(outPath, len(Drag.EventKinds)+len(Drag.HitKinds), "event and hit kinds")
}

func writeWireList(b *strings.Builder, name string, items []string) {
	fmt.Fprintf(b, "export const %s = [", name)
	for i, v := range items {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", v)
	}
	fmt.Fprintln(b, "] as const;")
}
