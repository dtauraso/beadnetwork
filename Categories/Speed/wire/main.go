package main

//go:generate go run .

import (
	"github.com/dtauraso/wirefold/scripts/genpaths"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/Scene/scenerun"
	Speed "github.com/dtauraso/wirefold/Categories/Speed"
)

func main() {
	genpaths.SetName("Categories/Speed/wire")
	_, srcRoot := genpaths.Roots()

	var b strings.Builder
	fmt.Fprintln(&b, "// GENERATED by Categories/Speed/wire — do not edit.")
	fmt.Fprintln(&b, "// Source: Speed.UpdateAttrs and Stdin's record_kinds.go.")
	fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "export const IN_KIND_EDIT_UPDATE = %d;\n\n", scenerun.KindEditUpdate)
	writeList(&b, "IN_UPDATE_ATTRS", Speed.UpdateAttrs)
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// EDIT_UPDATE_KINDS_START")
	writeList(&b, "IN_UPDATE_KINDS", scenerun.UpdateKinds)
	fmt.Fprintln(&b, "// EDIT_UPDATE_KINDS_END")
	fmt.Fprintln(&b)

	outPath := filepath.Join(srcRoot, "Speed", "wire-gen.ts")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		genpaths.Fatalf("write %s: %v", outPath, err)
	}
	genpaths.Announce(outPath, len(Speed.UpdateAttrs), "update attrs")
}

func writeList(b *strings.Builder, name string, items []string) {
	fmt.Fprintf(b, "export const %s = [", name)
	for i, v := range items {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", v)
	}
	fmt.Fprintln(b, "] as const;")
}
