package main

//go:generate go run .

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"

	"github.com/dtauraso/beadnetwork/scripts/genpaths"
)

func main() {
	genpaths.SetName("Categories/Node/Ports/kindports")
	repoRoot, srcRoot := genpaths.Roots()
	kinds := Kinds(repoRoot)

	outPath := filepath.Join(srcRoot, "Node", "Ports", "kind_ports_gen.go")
	if err := writeKindPorts(outPath, kinds); err != nil {
		genpaths.Fatalf("write %s: %v", outPath, err)
	}
	genpaths.Announce(outPath, len(kinds), "kinds")
}

func portDirExpr(p Port) (string, bool) {
	switch {
	case p.Direction == "in":
		return "PortIn", true
	case p.Direction == "out" && p.IsMulti:
		return "PortBroadcast", true
	case p.Direction == "out":
		return "PortOut", true
	}
	return "", false
}

func writeKindPorts(outPath string, kinds []KindEntry) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by Categories/Node/Ports/kindports — do not edit.`)
	fmt.Fprintln(w, `// Source: Categories/NodeKinds/<Kind>/SPEC.md ## Ports table.`)
	fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `package Ports`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KindPorts maps each runtime kind to the inputs and outputs its SPEC.md`)
	fmt.Fprintln(w, `// declares, in the same order the table lists them. Binding reads this`)
	fmt.Fprintln(w, `// instead of a hand-written list, so a kind declares its ports in one place`)
	fmt.Fprintln(w, `// and the runtime and the editor cannot disagree about them.`)
	fmt.Fprintln(w, `type PortDir int`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `const (`)
	fmt.Fprintln(w, "\tPortIn PortDir = iota")
	fmt.Fprintln(w, "\tPortOut")
	fmt.Fprintln(w, "\tPortBroadcast")
	fmt.Fprintln(w, `)`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `type PortSpec struct {`)
	fmt.Fprintln(w, "\tName string")
	fmt.Fprintln(w, "\tDir  PortDir")
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `func FirstPortOfDir(ports []PortSpec, dir PortDir) (string, bool) {`)
	fmt.Fprintln(w, "\tfor _, p := range ports {")
	fmt.Fprintln(w, "\t\tif p.Dir == dir {")
	fmt.Fprintln(w, "\t\t\treturn p.Name, true")
	fmt.Fprintln(w, "\t\t}")
	fmt.Fprintln(w, "\t}")
	fmt.Fprintln(w, "\treturn \"\", false")
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `var KindPorts = map[string][]PortSpec{`)
	for _, e := range kinds {
		fmt.Fprintf(w, "\t%q: {\n", e.GoKind)
		for _, p := range e.Ports {
			dir, ok := portDirExpr(p)
			if !ok {
				return fmt.Errorf("kind %q port %q: unknown direction %q", e.GoKind, p.ID, p.Direction)
			}
			fmt.Fprintf(w, "\t\t{Name: %q, Dir: %s},\n", p.ID, dir)
		}
		fmt.Fprintln(w, "\t},")
	}
	fmt.Fprintln(w, `}`)

	w.Flush()

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %v", err)
	}
	return genpaths.WriteIfChanged(outPath, formatted, 0o644)
}
