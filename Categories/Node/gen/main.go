package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	Node "github.com/dtauraso/wirefold/Categories/Node"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(Node.ValueRelTemplate), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Node/gen from NodeValueNames in node_values.go —\n")
	b.WriteString("// do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// One block file per node, written by that node's own goroutine. The row sits\n")
	b.WriteString("// in the path, not in the file.\n\n")
	b.WriteString("export const NODE_VALUE_NAMES = [\n")
	for _, name := range Node.NodeValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type NodeValueName = (typeof NODE_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genName = "Categories/Node/gen"
	_, srcRoot := roots()

	dir := filepath.Join(srcRoot, "Node")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		fatalf("write node paths: %v", err)
	}
	announce(pathsDir, 1, "node block path template")

	namesPath := filepath.Join(dir, "node-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		fatalf("write %s: %v", namesPath, err)
	}
	announce(namesPath, len(Node.NodeValueNames), "node values")

	writeWireTS(srcRoot)
}
