package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/beadnetwork/scripts/genpaths"

	"github.com/dtauraso/beadnetwork/Categories/Node/TopVector"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(TopVector.ValueRelTemplate), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Node/TopVector/layout from TopVectorValueNames in\n")
	b.WriteString("// top_vector_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// One block file per node, written by that node's own top-vector goroutine. The\n")
	b.WriteString("// row sits in the path, not in the file.\n\n")
	b.WriteString("export const TOP_VECTOR_VALUE_NAMES = [\n")
	for _, name := range TopVector.TopVectorValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type TopVectorValueName = (typeof TOP_VECTOR_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genpaths.SetName("Categories/Node/TopVector/layout")
	_, srcRoot := genpaths.Roots()

	dir := filepath.Join(srcRoot, "Node", "TopVector")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		genpaths.Fatalf("write top vector paths: %v", err)
	}
	genpaths.Announce(pathsDir, 1, "top vector block path template")

	namesPath := filepath.Join(dir, "top-vector-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(TopVector.TopVectorValueNames), "top vector values")
}
