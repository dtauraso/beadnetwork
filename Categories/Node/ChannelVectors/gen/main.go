package main

//go:generate go run .

import (
	"fmt"
	"github.com/dtauraso/wirefold/Categories/Node/nodegeom/gen/params"
	"os"
	"path/filepath"
	"strings"

	ChannelVectors "github.com/dtauraso/wirefold/Categories/Node/ChannelVectors"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(ChannelVectors.ValueRelTemplate), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Node/ChannelVectors/gen from VectorValueNames in\n")
	b.WriteString("// vector_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// One block file per node, holding the channel vectors leaving it. The row\n")
	b.WriteString("// sits in the path, not in the file.\n\n")
	b.WriteString("export const VECTOR_VALUE_NAMES = [\n")
	for _, name := range ChannelVectors.VectorValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type VectorValueName = (typeof VECTOR_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genName = "Categories/Node/ChannelVectors/gen"
	repoRoot, srcRoot := roots()

	dir := filepath.Join(srcRoot, "Node", "ChannelVectors")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		fatalf("write channel vector paths: %v", err)
	}
	announce(pathsDir, 1, "channel vector block path template")

	namesPath := filepath.Join(dir, "vector-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		fatalf("write %s: %v", namesPath, err)
	}
	announce(namesPath, len(ChannelVectors.VectorValueNames), "channel vector values")

	shGo := filepath.Join(dir, "shading_params.go")
	shParams, shErr := params.ParseShadingParams(repoRoot, shGo)
	if shErr != nil {
		fatalf("parse shading params: %v", shErr)
	}
	shTs := filepath.Join(dir, "shading-params.ts")
	if err := params.WriteShadingParams(shTs, shParams, genName, "Categories/Node/ChannelVectors/shading_params.go"); err != nil {
		fatalf("write %s: %v", shTs, err)
	}
	announce(shTs, len(shParams), "channel constants")
}
