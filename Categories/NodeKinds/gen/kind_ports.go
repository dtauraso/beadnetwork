package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/NodeKinds/gen/kindscan"
)

func portDirExpr(p kindscan.Port) (string, bool) {
	switch {
	case p.Direction == "in":
		return "PortIn", true
	case p.Direction == "out" && p.IsMulti:
		return "PortBroadcast", true
	case p.Direction == "out":
		return "PortOut", true
	}
	return "", false
}

func writeKindPorts(outPath, pkg string, kinds []kindscan.KindEntry) error {
	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, `// GENERATED by Categories/NodeKinds/gen — do not edit.`)
	fmt.Fprintln(w, `// Source: Categories/NodeKinds/<Kind>/SPEC.md ## Ports table.`)
	fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
	fmt.Fprintln(w)
	fmt.Fprintf(w, "package %s\n", pkg)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `// KindPorts maps each runtime kind to the inputs and outputs its SPEC.md`)
	fmt.Fprintln(w, `// declares, in the same order the table lists them. BuilderFor reads`)
	fmt.Fprintln(w, `// this instead of taking a hand-written list, so a kind declares its ports`)
	fmt.Fprintln(w, `// in one place and the runtime and the editor cannot disagree about them.`)
	fmt.Fprintln(w, `type PortDir int`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `const (`)
	fmt.Fprintln(w, "\tPortIn PortDir = iota")
	fmt.Fprintln(w, "\tPortOut")
	fmt.Fprintln(w, "\tPortBroadcast")
	fmt.Fprintln(w, `)`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `type PortSpec struct {`)
	fmt.Fprintln(w, "\tName string")
	fmt.Fprintln(w, "\tDir  PortDir")
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `func FirstPortOfDir(ports []PortSpec, dir PortDir) (string, bool) {`)
	fmt.Fprintln(w, "\tfor _, p := range ports {")
	fmt.Fprintln(w, "\t\tif p.Dir == dir {")
	fmt.Fprintln(w, "\t\t\treturn p.Name, true")
	fmt.Fprintln(w, "\t\t}")
	fmt.Fprintln(w, "\t}")
	fmt.Fprintln(w, "\treturn \"\", false")
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `var KindPorts = map[string][]PortSpec{`)
	for _, e := range kinds {
		fmt.Fprintf(w, "\t%q: {\n", e.GoKind)
		for _, p := range e.Ports {
			dir, ok := portDirExpr(p)
			if !ok {
				return fmt.Errorf("kind %q port %q: unknown direction %q", e.GoKind, p.ID, p.Direction)
			}
			fmt.Fprintf(w, "\t\t{Name: %q, Dir: %s},\n", p.ID, dir)
		}
		fmt.Fprintln(w, "\t},")
	}
	fmt.Fprintln(w, `}`)

	w.Flush()

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %v", err)
	}
	return os.WriteFile(outPath, formatted, 0o644)
}

func packageNameIn(dir string) (string, error) {
	f, err := os.ReadFile(filepath.Join(dir, "node.go"))
	if err != nil {
		return "", fmt.Errorf("read package name for %s: %v", dir, err)
	}
	for _, line := range strings.Split(string(f), "\n") {
		if strings.HasPrefix(line, "package ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "package ")), nil
		}
	}
	return "", fmt.Errorf("no package clause in %s/node.go", dir)
}

func writeKindOwnPorts(kindsDir string, kinds []kindscan.KindEntry) error {
	for _, e := range kinds {
		var buf bytes.Buffer
		w := bufio.NewWriter(&buf)

		fmt.Fprintln(w, `// GENERATED by Categories/NodeKinds/gen — do not edit.`)
		fmt.Fprintln(w, `// Source: this kind's own SPEC.md ## Ports table.`)
		fmt.Fprintln(w, `// Regenerate with: go generate ./...`)
		fmt.Fprintln(w)
		pkg, err := packageNameIn(filepath.Join(kindsDir, e.Dir))
		if err != nil {
			return err
		}
		fmt.Fprintf(w, "package %s\n", pkg)
		fmt.Fprintln(w)
		fmt.Fprintln(w, `// kindPorts is what this kind's SPEC.md declares, in the order the table`)
		fmt.Fprintln(w, `// lists it. BuilderFor reads this rather than a shared map, so the ports a`)
		fmt.Fprintln(w, `// kind may bind are declared in the kind and nowhere else.`)
		fmt.Fprintln(w, `var kindPorts = []PortSpec{`)
		for _, p := range e.Ports {
			dir, ok := portDirExpr(p)
			if !ok {
				return fmt.Errorf("kind %q port %q: unknown direction %q", e.GoKind, p.ID, p.Direction)
			}
			fmt.Fprintf(w, "\t{Name: %q, Dir: %s},\n", p.ID, dir)
		}
		fmt.Fprintln(w, `}`)

		w.Flush()
		formatted, err := format.Source(buf.Bytes())
		if err != nil {
			return fmt.Errorf("format %s: %v", e.GoKind, err)
		}
		out := filepath.Join(kindsDir, e.Dir, "kind_ports_gen.go")
		if err := os.WriteFile(out, formatted, 0o644); err != nil {
			return err
		}
	}
	return nil
}
