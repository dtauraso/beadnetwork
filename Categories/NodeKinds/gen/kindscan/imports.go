package kindscan

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
)

func WriteKindImports(outPath, networkPkg string, kinds []KindEntry) error {
	sorted := append([]KindEntry{}, kinds...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Dir < sorted[j].Dir })

	var buf bytes.Buffer
	buf.WriteString("// Code generated by Categories/NodeKinds/gen. DO NOT EDIT.\n\n")
	buf.WriteString("// One case per kind, naming that kind's Builder. A kind missing from here is\n")
	buf.WriteString("// a scene type nothing can build, and BuilderFor says so by name rather than\n")
	buf.WriteString("// returning a zero builder that fails later.\n")
	buf.WriteString("package NodeKinds\n\nimport (\n")
	for _, k := range sorted {
		fmt.Fprintf(&buf, "\t%s %q\n", pkgAlias(k.Dir), networkPkg+"/"+k.Dir)
	}
	fmt.Fprintf(&buf, "\n\t%q\n", networkPkg+"/kindreg")
	buf.WriteString(")\n\n")

	buf.WriteString("func BuilderFor(kind string) (kindreg.NodeBuilder, bool) {\n")
	buf.WriteString("\tswitch kind {\n")
	for _, k := range sorted {
		fmt.Fprintf(&buf, "\tcase %q:\n\t\treturn %s.Builder, true\n", k.GoKind, pkgAlias(k.Dir))
	}
	buf.WriteString("\t}\n\treturn kindreg.NodeBuilder{}, false\n}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile(outPath, formatted, 0644)
}

func pkgAlias(dir string) string { return "kind" + dir }
