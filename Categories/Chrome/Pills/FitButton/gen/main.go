package main

//go:generate go run .

import (
	"github.com/dtauraso/wirefold/scripts/genpaths"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/Chrome/Pills/FitButton"
)

func writePathFiles(pathsDir string) error {
	if err := os.MkdirAll(pathsDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(pathsDir, "block.bin"), []byte(FitButton.ValueRelPath()), 0o644); err != nil {
		return err
	}
	entries, err := os.ReadDir(pathsDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == "block.bin" { // path-resolution-ok: the generator's own output directory
			continue
		}
		if err := os.Remove(filepath.Join(pathsDir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeNames(path string) error {
	var b strings.Builder
	b.WriteString("// GENERATED by Categories/Chrome/Pills/FitButton/gen from ChipValueNames in\n")
	b.WriteString("// chip_values.go — do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The fit chip's values, each one file under the scene root. The renderer learns\n")
	b.WriteString("// where from Categories/Chrome/Pills/FitButton/paths/, which Go writes from this same\n")
	b.WriteString("// list, so neither side spells a path.\n\n")
	b.WriteString("export const FIT_CHIP_VALUE_NAMES = [\n")
	for _, name := range FitButton.ChipValueNames {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type FitChipValueName = (typeof FIT_CHIP_VALUE_NAMES)[number];\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func main() {
	genpaths.SetName("FitButton/gen")
	_, srcRoot := genpaths.Roots()

	dir := filepath.Join(srcRoot, "Chrome", "Pills", "FitButton")
	pathsDir := filepath.Join(dir, "paths")
	if err := writePathFiles(pathsDir); err != nil {
		genpaths.Fatalf("write fit chip paths: %v", err)
	}
	genpaths.Announce(pathsDir, len(FitButton.ChipValueNames), "fit chip paths")

	namesPath := filepath.Join(dir, "chip-values-gen.ts")
	if err := writeNames(namesPath); err != nil {
		genpaths.Fatalf("write %s: %v", namesPath, err)
	}
	genpaths.Announce(namesPath, len(FitButton.ChipValueNames), "fit chip values")
}
