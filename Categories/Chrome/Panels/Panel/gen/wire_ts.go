package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/dtauraso/wirefold/Categories/Chrome/Panels/Panel"
	"github.com/dtauraso/wirefold/Categories/Scene/scenerun"
)

func writeWireTS(srcRoot string) {
	var b strings.Builder
	fmt.Fprintln(&b, "// GENERATED by Categories/Chrome/Panels/Panel/gen — do not edit.")
	fmt.Fprintln(&b, "// Source: Panel.UpdateAttrs and Stdin's record_kinds.go.")
	fmt.Fprintln(&b, "// Regenerate with: go generate ./...")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "export const IN_KIND_EDIT_UPDATE = %d;\n\n", scenerun.KindEditUpdate)
	writeWireList(&b, "IN_UPDATE_ATTRS", Panel.UpdateAttrs)
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// EDIT_UPDATE_KINDS_START")
	writeWireList(&b, "IN_UPDATE_KINDS", scenerun.UpdateKinds)
	fmt.Fprintln(&b, "// EDIT_UPDATE_KINDS_END")
	fmt.Fprintln(&b)

	outPath := filepath.Join(srcRoot, "Chrome", "Panels", "Panel", "wire-gen.ts")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}
	announce(outPath, len(Panel.UpdateAttrs), "update attrs")
}

func writeWireList(b *strings.Builder, name string, items []string) {
	fmt.Fprintf(b, "export const %s = [", name)
	for i, v := range items {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", v)
	}
	fmt.Fprintln(b, "] as const;")
}
